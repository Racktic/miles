"""Zero-shot, no-summary Alchemy eval for frontier models, aligned with Sawyer et al. (2025).

For each episode: drive `AlchemyTextEnv` (20 steps/trial, 10 trials, end-trial enabled) as a multi-turn
chat. Every turn the user message is the TMLR `GAME STATE UPDATE` (`render_game_state`) and the
assistant message is the model's full `OBSERVATION/REASONING/ACTION` response — **the entire history
stays in context every turn (no summary, no memory writes)**, exactly the TMLR no-summary condition.
One model response == one env step (invalid/unparseable responses are charged a wasted no-op step, so
the env's own 10*20 budget bounds the loop). Per trial we score `agent / oracle` (normalized-to-oracle)
and report mean performance + I_score (cross-trial improvement). Results stream to JSONL.

  python -m examples.alchemy.eval.eval_alchemy --provider anthropic --model claude-opus-4-8 --n-episodes 10
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import threading
import time
import traceback
from concurrent.futures import ThreadPoolExecutor, as_completed

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(_HERE))  # examples/alchemy  (for env_alchemy)
sys.path.insert(0, _HERE)                    # eval/             (for sibling modules)

from env_alchemy import AlchemyTextEnv, _stone_desc, decode_obs  # noqa: E402
from llm_client import make_client  # noqa: E402
from oracle import normalize, oracle_per_trial  # noqa: E402
from prompts_eval import (build_eval_system, parse_eval_action, render_game_state,  # noqa: E402
                          SUMMARY_SYSTEM, SUMMARY_INSTRUCTION)

N_TRIALS = 10  # TMLR setting


def _improve(scores):
    """Robust cross-trial improvement: mean(last 5 trials) - mean(first 5 trials).
    `scores` may contain None (oracle-undefined trials); those are dropped per half."""
    first = [x for x in scores[:5] if x is not None]
    last = [x for x in scores[5:] if x is not None]
    if not first or not last:
        return None
    return sum(last) / len(last) - sum(first) / len(first)


def _improve_tmlr(scores):
    """TMLR's exact I_score: mean(last 5 trials) - trial 1 (kept for paper comparison)."""
    last = [x for x in scores[5:] if x is not None]
    if not last or scores[0] is None:
        return None
    return sum(last) / len(last) - scores[0]


def _build_last(parsed: dict, new_obs: dict, reward: float) -> dict:
    """The echo block for the NEXT turn: outcome stone (potion), or a one-line note (cauldron/
    end-trial/invalid)."""
    last = {"kind": parsed.get("kind"), "stone": parsed.get("stone"),
            "potion": parsed.get("potion"), "outcome_desc": None, "note": None}
    if not parsed.get("valid"):
        last["kind"] = None
        last["note"] = (f"Your last response was not a valid action "
                        f"({parsed.get('reason') or 'could not parse an ACTION line'}); "
                        f"it was skipped as a no-op. Reply with exactly one ACTION.")
        return last
    if parsed["kind"] == "potion":
        s = decode_obs(new_obs["vec"])["stones"][parsed["stone"]]
        if s["exists"]:
            desc, rwd = _stone_desc(s["axes"], s["value"])
            last["outcome_desc"] = f"{desc} with reward {rwd:+d}"
        else:
            last["outcome_desc"] = "(the stone is gone)"
    elif parsed["kind"] == "cauldron":
        last["note"] = (f"You placed stone {parsed['stone']} in the cauldron and "
                        f"scored {int(round(reward)):+d}.")
    elif parsed["kind"] == "end_trial":
        last["note"] = "You ended the trial."
    return last


def _gen_summary(client, trial_messages: list, prev_summary: str | None) -> str:
    """REWRITE step (TMLR A.4.2): summarise the just-finished trial + previous summary."""
    instr = SUMMARY_INSTRUCTION
    if prev_summary:
        instr = f"Your previous summary:\n{prev_summary}\n\n{instr}"
    return client.complete(SUMMARY_SYSTEM, trial_messages + [{"role": "user", "content": instr}]) or ""


def run_episode(client, episode_index: int, max_steps_per_trial: int, hard_cap: int,
                fout, system: str, oracle_mode: str = "skip", traj_dir: str | None = None,
                write_lock=None, summary: bool = False, summary_mode: str = "augment",
                inject_summaries: list | None = None) -> dict:
    # inject_summaries (writer/reader disentangle experiment): when given, the per-trial memory is NOT
    # generated by this client; instead the pre-written external summaries M_1..M_9 (e.g. Qwen's) are
    # folded in at each trial boundary, and THIS client only does the memory-conditioned ACT. Requires
    # replace mode (memory is the sole cross-trial carrier -> clean: the reader plays each trial on the
    # external memory alone, regardless of how it played the previous trial). See L_WM_DESIGN-adjacent
    # discussion / BASELINE_RESULTS.md.
    env = AlchemyTextEnv(episode_index=episode_index, num_trials=N_TRIALS,
                         max_steps_per_trial=max_steps_per_trial, end_trial_action=True)
    obs = env.reset()
    messages: list[dict] = []          # chat sent to the model (full history; reset per trial if replace)
    trial_messages: list[dict] = []    # current trial's turns only (input to the summary REWRITE)
    transcript: list[dict] = []
    summaries: list[str] = []
    summary_text: str | None = None
    last = None
    first = True
    first_of_trial = True
    invalid = 0
    turns = 0
    done = False
    while not done and turns < hard_cap:
        user_text = render_game_state(obs, last=last, first_turn=first)
        if summary and first_of_trial and summary_text:   # fold the carried memory into the trial's 1st turn
            user_text = (f"[Summary of what you've learned so far this episode]\n{summary_text}\n\n"
                         f"{user_text}")
        messages.append({"role": "user", "content": user_text})
        trial_messages.append({"role": "user", "content": user_text})
        resp = client.complete(system, messages) or ""
        messages.append({"role": "assistant", "content": resp})
        trial_messages.append({"role": "assistant", "content": resp})
        parsed = parse_eval_action(resp, obs=obs)
        if not parsed.get("valid"):
            invalid += 1
            action_int = env.num_special - 1            # no-op: wastes the step (bounded by env)
        else:
            action_int = parsed["action"]
        obs, reward, done, _ = env.step(action_int)
        transcript.append({"turn": turns, "trial": obs["trial"], "user": user_text,
                           "assistant": resp, "parsed": parsed, "reward": reward})
        last = _build_last(parsed, obs, reward)
        first = False
        first_of_trial = False
        turns += 1
        if summary and obs["new_trial"] and not done:     # a trial just ended -> REWRITE the summary
            if inject_summaries is not None:               # use external (e.g. Qwen) memory; reader doesn't write
                idx = len(summaries)
                summary_text = inject_summaries[idx] if idx < len(inject_summaries) else summary_text
            else:
                summary_text = _gen_summary(client, trial_messages, summary_text)
            summaries.append(summary_text)
            trial_messages = []
            if summary_mode == "replace":                 # memory REPLACES history for the next trial
                messages = []
            first_of_trial = True

    agent = list(env.per_trial_scores)[:N_TRIALS]
    agent += [0.0] * (N_TRIALS - len(agent))            # pad if it ended early
    total_reward = env.total_reward
    env.close()

    if traj_dir is not None:                            # full chat trace for inspection/debugging
        os.makedirs(traj_dir, exist_ok=True)
        with open(os.path.join(traj_dir, f"ep{episode_index}.json"), "w") as tf:
            json.dump({"episode_index": episode_index, "system": system,
                       "summaries": summaries, "transcript": transcript}, tf, indent=2)

    # raw metrics (always available, oracle-free): mean trial score + raw cross-trial improvement.
    # Primary I_score = mean(last5) - mean(first5) (more robust than TMLR's single-trial-1 baseline);
    # raw_i_score_tmlr keeps the paper's exact mean(last5)-trial1 for direct comparison.
    raw_performance = sum(agent) / len(agent)
    raw_i_score = _improve(agent)
    raw_i_score_tmlr = _improve_tmlr(agent)

    # normalized-to-oracle metrics are OPTIONAL here: the ideal observer is expensive, so by default
    # we defer it (oracle_mode="skip") and resolve normalization later from a cached oracle table
    # (see compute_oracle.py / finalize.py). oracle_mode="inline" computes it now (may be slow).
    oracle = norm = performance = i_score = i_score_tmlr = None
    if oracle_mode == "inline":
        try:
            oracle = list(oracle_per_trial(episode_index))
            norm = normalize(agent, oracle)             # None where oracle<=0
            valid_norm = [x for x in norm if x is not None]
            performance = sum(valid_norm) / len(valid_norm) if valid_norm else None
            i_score = _improve(norm)
            i_score_tmlr = _improve_tmlr(norm)
        except Exception as e:
            print(f"[eval] oracle for ep {episode_index} failed/skipped: {e}", flush=True)

    rec = {
        "episode_index": episode_index, "turns": turns, "invalid_actions": invalid,
        "agent_per_trial": agent, "oracle_per_trial": oracle, "normalized_per_trial": norm,
        "performance": performance, "i_score": i_score, "i_score_tmlr": i_score_tmlr,
        "raw_performance": raw_performance, "raw_i_score": raw_i_score,
        "raw_i_score_tmlr": raw_i_score_tmlr,
        "total_reward": total_reward, "usage": dict(client.usage), "refusals": client.refusals,
    }
    import contextlib
    with (write_lock or contextlib.nullcontext()):          # serialise the shared results.jsonl write
        fout.write(json.dumps(rec) + "\n")
        fout.flush()
    return rec


def _parse_episode_spec(spec: str) -> list:
    """'1,3,6-9' -> [1,3,6,7,8,9]."""
    out = []
    for part in spec.split(","):
        part = part.strip()
        if "-" in part:
            a, b = part.split("-")
            out.extend(range(int(a), int(b) + 1))
        elif part:
            out.append(int(part))
    return out


def _mean(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None


def _stderr(xs):
    xs = [x for x in xs if x is not None]
    if len(xs) < 2:
        return None
    m = sum(xs) / len(xs)
    var = sum((x - m) ** 2 for x in xs) / (len(xs) - 1)
    return (var / len(xs)) ** 0.5


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--provider", default="anthropic")
    ap.add_argument("--model", default="claude-opus-4-8")
    ap.add_argument("--n-episodes", type=int, default=N_TRIALS)
    ap.add_argument("--start", type=int, default=0, help="first episode_index (contiguous mode)")
    ap.add_argument("--episodes", default=None,
                    help="explicit episode list, e.g. '1,3,6-9'; overrides --start/--n-episodes")
    ap.add_argument("--episode-file", default=None,
                    help="JSON file with an 'episodes' list (e.g. hard_set_20.json); overrides --start/--n-episodes")
    ap.add_argument("--max-steps-per-trial", type=int, default=20)
    ap.add_argument("--max-tokens", type=int, default=2048)
    ap.add_argument("--base-url", default=None,
                    help="OpenAI-compatible endpoint for provider=openai (e.g. local Qwen via sglang: "
                         "http://localhost:30000/v1). Omit for OpenAI cloud.")
    ap.add_argument("--reasoning-effort", default=None,
                    help="reasoning effort for GPT-5/o-series (e.g. low/medium/high).")
    ap.add_argument("--temperature", type=float, default=None, help="sampling temperature (None=default).")
    ap.add_argument("--no-thinking", action="store_true",
                    help="Qwen/OpenAI-compat: disable the model's thinking mode "
                         "(sets extra_body chat_template_kwargs.enable_thinking=false). Needed for "
                         "Qwen3.5 so reasoning doesn't eat the token budget before the ACTION line.")
    ap.add_argument("--extra-body", default=None,
                    help="raw JSON dict passed as extra_body to the OpenAI-compat call (advanced).")
    ap.add_argument("--workers", type=int, default=1,
                    help="parallel episodes (turns within an episode stay serial). 5-6 is a safe "
                         "concurrency vs API rate limits; 1 = serial.")
    ap.add_argument("--prior-info", action="store_true",
                    help="include the paper's prior-information block (reward/potion-pairing/causal "
                         "invariants) -> Figure 5b condition; omit for the no-prior-info Figure 5a.")
    ap.add_argument("--summary", action="store_true",
                    help="cross-trial summarization (TMLR A.4.2): write a summary at each trial boundary "
                         "and act on it in later trials. Off = no-summary (full history every turn).")
    ap.add_argument("--summary-mode", choices=["replace", "augment"], default="augment",
                    help="replace: summary REPLACES the prior-trial history; augment: summary is folded "
                         "in on top of the full growing history.")
    ap.add_argument("--inject-summaries", default=None,
                    help="writer/reader disentangle: a prior run dir (e.g. a qwen replace run); its per-episode "
                         "traj/ep*.json 'summaries' are injected as the memory instead of THIS model writing it. "
                         "Forces --summary --summary-mode replace. This model only does memory-conditioned ACT.")
    ap.add_argument("--oracle-mode", choices=["skip", "inline"], default="skip",
                    help="skip (default): defer the expensive ideal-observer oracle, only raw scores; "
                         "inline: compute normalized-to-oracle now (slow).")
    ap.add_argument("--extra-system-file", default=None,
                    help="path to a text file whose contents are APPENDED to the system prompt "
                         "(prompt-iteration hook, e.g. exploration guidance for Qwen3-4B).")
    ap.add_argument("--out-dir", default=None)
    args = ap.parse_args()

    if args.inject_summaries:                               # injection => external memory, replace mode
        args.summary = True
        args.summary_mode = "replace"
    system = build_eval_system(prior_info=args.prior_info)
    if args.extra_system_file:                              # prompt-iteration: append extra guidance
        with open(args.extra_system_file) as f:
            system = system + "\n\n" + f.read().strip()
    sumtag = (f"sum-{args.summary_mode}" if args.summary else "nosum")
    inj_tag = ""
    if args.inject_summaries:
        src = os.path.basename(os.path.normpath(args.inject_summaries)).replace("eval-", "")
        inj_tag = f"-inject[{src}]"
    cond = f"{sumtag}{inj_tag}-{'prior' if args.prior_info else 'noprior'}"

    # resolve which episodes to run: explicit file > explicit spec > contiguous range
    if args.episode_file:
        episodes = list(json.load(open(args.episode_file))["episodes"])
    elif args.episodes:
        episodes = _parse_episode_spec(args.episodes)
    else:
        episodes = list(range(args.start, args.start + args.n_episodes))

    ts = time.strftime("%Y%m%d-%H%M%S")
    out_dir = args.out_dir or os.path.join(
        os.path.dirname(os.path.dirname(_HERE)), "alchemy", "logs",
        f"eval-{args.model}-{cond}-{ts}")
    out_dir = os.path.abspath(out_dir)
    os.makedirs(out_dir, exist_ok=True)
    results_path = os.path.join(out_dir, "results.jsonl")
    print(f"[eval] provider={args.provider} model={args.model} condition={cond} "
          f"n={len(episodes)} episodes={episodes} -> {results_path}", flush=True)

    extra_body = json.loads(args.extra_body) if args.extra_body else None
    if args.no_thinking:
        extra_body = {"chat_template_kwargs": {"enable_thinking": False}}
    client = make_client(args.provider, args.model, max_tokens=args.max_tokens,
                         base_url=args.base_url, reasoning_effort=args.reasoning_effort,
                         temperature=args.temperature, extra_body=extra_body)
    hard_cap = N_TRIALS * args.max_steps_per_trial + 30
    recs = []
    write_lock = threading.Lock()

    def _report(idx, rec):
        recs.append(rec)
        print(f"[eval] ep {idx}: raw_perf={rec['raw_performance']:.2f} "
              f"raw_I={rec['raw_i_score']:.2f} norm_perf={rec['performance']} "
              f"invalid={rec['invalid_actions']}/{rec['turns']} "
              f"agent={[round(x, 1) for x in rec['agent_per_trial']]}", flush=True)

    def _load_injected(idx):
        if not args.inject_summaries:
            return None
        p = os.path.join(args.inject_summaries, "traj", f"ep{idx}.json")
        sm = json.load(open(p))["summaries"]
        if not sm:
            raise ValueError(f"no summaries in {p}")
        return sm

    with open(results_path, "w") as fout:
        def _run(idx):
            return run_episode(client, idx, args.max_steps_per_trial, hard_cap, fout,
                               system=system, oracle_mode=args.oracle_mode,
                               traj_dir=os.path.join(out_dir, "traj"), write_lock=write_lock,
                               summary=args.summary, summary_mode=args.summary_mode,
                               inject_summaries=_load_injected(idx))
        if args.workers <= 1:
            for idx in episodes:
                try:
                    _report(idx, _run(idx))
                except Exception as e:
                    print(f"[eval] episode {idx} FAILED: {e}\n{traceback.format_exc()}", flush=True)
        else:
            with ThreadPoolExecutor(max_workers=args.workers) as ex:  # episodes parallel, turns serial
                futs = {ex.submit(_run, idx): idx for idx in episodes}
                for fut in as_completed(futs):
                    idx = futs[fut]
                    try:
                        _report(idx, fut.result())
                    except Exception as e:
                        print(f"[eval] episode {idx} FAILED: {e}\n{traceback.format_exc()}", flush=True)

    # --- integrated normalization (was a separate finalize.py step) ---
    # Fill normalized-to-oracle scores from the cached oracle table, so a plain run already reports
    # normalized performance/I_score (no need to run finalize.py afterwards). Cached oracle is the
    # authoritative per-trial optimum; covers all 1000 prebuilt episodes.
    _ocp = os.path.join(os.path.dirname(os.path.abspath(__file__)), "oracle_cache.json")
    if os.path.exists(_ocp):
        _oc = json.load(open(_ocp))
        for r in recs:
            o = _oc.get(str(r["episode_index"]))
            if not o:
                continue
            ag = r["agent_per_trial"]
            norm = [None if (i >= len(o) or o[i] <= 0) else float(ag[i]) / float(o[i]) for i in range(len(ag))]
            vals = [x for x in norm if x is not None]
            f5 = [x for x in norm[:5] if x is not None]
            l5 = [x for x in norm[5:] if x is not None]
            r["normalized_per_trial"] = norm
            r["performance"] = (sum(vals) / len(vals)) if vals else None
            r["i_score"] = (sum(l5) / len(l5) - sum(f5) / len(f5)) if (f5 and l5) else None
            r["i_score_tmlr"] = (sum(l5) / len(l5) - norm[0]) if (l5 and norm[0] is not None) else None

    perf_m, perf_se = _mean([r["performance"] for r in recs]), _stderr([r["performance"] for r in recs])
    i_m, i_se = _mean([r["i_score"] for r in recs]), _stderr([r["i_score"] for r in recs])
    i_tm, i_tse = _mean([r.get("i_score_tmlr") for r in recs]), _stderr([r.get("i_score_tmlr") for r in recs])
    rperf_m, rperf_se = _mean([r["raw_performance"] for r in recs]), _stderr([r["raw_performance"] for r in recs])
    ri_m, ri_se = _mean([r["raw_i_score"] for r in recs]), _stderr([r["raw_i_score"] for r in recs])
    ri_tm, ri_tse = _mean([r.get("raw_i_score_tmlr") for r in recs]), _stderr([r.get("raw_i_score_tmlr") for r in recs])
    summary = {"model": args.model, "n_episodes": len(recs), "condition": cond,
               "prior_info": args.prior_info, "oracle_mode": args.oracle_mode,
               "performance_mean": perf_m, "performance_se": perf_se,
               "i_score_mean": i_m, "i_score_se": i_se,
               "i_score_tmlr_mean": i_tm, "i_score_tmlr_se": i_tse,
               "raw_performance_mean": rperf_m, "raw_performance_se": rperf_se,
               "raw_i_score_mean": ri_m, "raw_i_score_se": ri_se,
               "raw_i_score_tmlr_mean": ri_tm, "raw_i_score_tmlr_se": ri_tse,
               "total_usage": dict(client.usage), "refusals": client.refusals}
    with open(os.path.join(out_dir, "summary.json"), "w") as f:
        json.dump(summary, f, indent=2)
    print(f"\n[eval] === SUMMARY (N={len(recs)}) ===", flush=True)
    print(f"  raw performance (mean trial score):     {rperf_m}  (SE {rperf_se})", flush=True)
    print(f"  raw I_score (last5 mean - first5 mean): {ri_m}  (SE {ri_se})", flush=True)
    print(f"  raw I_score [TMLR: last5 mean - tr1]:   {ri_tm}  (SE {ri_tse})", flush=True)
    print(f"  normalized-to-oracle performance:       {perf_m}  (SE {perf_se})  [cached-oracle]", flush=True)
    print(f"  normalized I_score (last5 - first5):    {i_m}  (SE {i_se})", flush=True)
    print(f"  normalized I_score [TMLR: last5 - tr1]: {i_tm}  (SE {i_tse})", flush=True)
    print(f"  usage: {client.usage}  refusals: {client.refusals}", flush=True)
    print(f"  -> {out_dir}", flush=True)


if __name__ == "__main__":
    main()
